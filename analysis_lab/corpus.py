def load_cases(source: Path | None = None) -> list[dict]:
    if source and source.exists():
        cases = yaml.safe_load(source.read_text(encoding="utf-8"))
    else:
        cases = []
        for mode in MODES:
            for split, families in FAMILIES[mode].items():
                for number, (subtype, line) in enumerate(families):
                    family = f"{mode}:{split}:{number:02d}"
                    phrases = line.split("|")
                    assert len(phrases) == 10, (family, len(phrases))
                    for i, text in enumerate(phrases):
                        cases.append({"id": f"{family}:{i:02d}", "text": text,
                                      "mode": mode, "split": split, "family": family,
                                      "subtype": subtype, "source": "synthetic_authored"})
    validate_cases(cases)
    return cases


def validate_cases(cases: list[dict]) -> None:
    if not isinstance(cases, list):
        raise ValueError("案例配置必须是列表")
    seen_texts, seen_ids, families = set(), set(), {}
    counts = Counter()
    for case in cases:
        if case.get("mode") not in MODES or case.get("split") not in {"train", "validation", "test"}:
            raise ValueError(f"非法分类或集合：{case}")
        text = normalize_text(case.get("text", ""))
        if not text or len(case["text"]) > 256 or text in seen_texts or case["id"] in seen_ids:
            raise ValueError(f"空句、超长句或重复案例：{case}")
        seen_texts.add(text)
        seen_ids.add(case["id"])
        family = case["family"]
        if family in families and families[family] != case["split"]:
            raise ValueError(f"表达家族跨集合：{family}")
        families[family] = case["split"]
        counts[case["mode"], case["split"]] += 1
    for mode in MODES:
        if not 100 <= sum(counts[mode, s] for s in ("train", "validation", "test")) <= 200:
            raise ValueError(f"{mode} 必须有 100–200 条案例")
        if any(counts[mode, s] < 10 for s in ("train", "validation", "test")):
            raise ValueError(f"{mode} 的每个集合至少需要 10 条案例")
